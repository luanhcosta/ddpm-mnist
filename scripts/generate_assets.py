"""Generate all blog post assets that don't require a trained model.

This script can be run immediately after setup — no training needed.
It produces the conceptual visuals for the blog post:

    noise_schedule.png        — β, ᾱ, signal/noise amplitude, SNR over T
    noising_trajectory.png    — a real MNIST digit being progressively noised

Assets that DO require a trained model (generated by other scripts):
    loss_curve.png            — scripts/train.py --assets-dir
    samples_final.png         — scripts/train.py --assets-dir  (or sample.py)
    denoising.gif             — scripts/train.py --assets-dir  (or sample.py --gif)
    samples_ddim.png          — scripts/sample.py --ddim --assets-dir
    h2d_bandwidth.png         — scripts/benchmark.py --assets-dir
    dataloader_comparison.png — scripts/benchmark.py --assets-dir
    sampling_comparison.png   — scripts/benchmark.py --assets-dir
    training_breakdown.png    — scripts/benchmark.py --assets-dir

Usage:
    python scripts/generate_assets.py --assets-dir ../blog-luan-costa/static/images/ddpm
    python scripts/generate_assets.py --assets-dir ../blog-luan-costa/static/images/ddpm --schedule cosine
"""

import argparse
import sys
from pathlib import Path

import torch

sys.path.insert(0, str(Path(__file__).parent.parent))

from config.config import DiffusionConfig, DataConfig
from data.dataset import get_dataloader
from models.diffusion import make_beta_schedule, DiffusionProcess
from utils.visualization import plot_noise_schedule, plot_noising_trajectory


def parse_args():
    p = argparse.ArgumentParser()
    p.add_argument(
        "--assets-dir",
        required=True,
        help="Destination for blog images (e.g. ../blog-luan-costa/static/images/ddpm)",
    )
    p.add_argument("--schedule", choices=["linear", "cosine"], default="linear")
    p.add_argument("--timesteps", type=int, default=1000)
    p.add_argument("--output-dir", default="results/plots", help="Primary save location")
    p.add_argument("--device", default="cuda" if torch.cuda.is_available() else "cpu")
    return p.parse_args()


def generate_noise_schedule(args, assets_dir: Path, output_dir: Path) -> None:
    print("\n[1/2] Noise schedule plot...")
    cfg = DiffusionConfig(timesteps=args.timesteps, schedule=args.schedule)
    betas = make_beta_schedule(cfg.timesteps, cfg.beta_start, cfg.beta_end, cfg.schedule)
    plot_noise_schedule(
        betas,
        output_dir / "noise_schedule.png",
        assets_dir=assets_dir,
        assets_name="noise_schedule.png",
    )


def generate_noising_trajectory(args, assets_dir: Path, output_dir: Path) -> None:
    print("\n[2/2] Noising trajectory (requires MNIST download)...")
    device = torch.device(args.device)

    cfg_data = DataConfig(batch_size=1, num_workers=0, pin_memory=False)
    cfg_diff = DiffusionConfig(timesteps=args.timesteps, schedule=args.schedule)

    loader = get_dataloader(cfg_data)
    diffusion = DiffusionProcess(cfg_diff, device)

    # Pick the first image from the dataset
    x0, label = next(iter(loader))
    x0 = x0.to(device)
    digit = label[0].item()
    print(f"  Using digit: {digit}")

    # Apply q_sample at a range of timesteps
    show_at = [0, 100, 250, 500, 750, 999]
    images_at_steps = []
    for t_val in show_at:
        t_tensor = torch.tensor([t_val], device=device)
        if t_val == 0:
            img = x0[0].cpu()
        else:
            noised = diffusion.q_sample(x0, t_tensor)
            img = noised[0].cpu()
        images_at_steps.append((t_val, img))

    plot_noising_trajectory(
        images_at_steps,
        output_dir / "noising_trajectory.png",
        assets_dir=assets_dir,
        assets_name="noising_trajectory.png",
    )


def main():
    args = parse_args()
    assets_dir = Path(args.assets_dir)
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    assets_dir.mkdir(parents=True, exist_ok=True)

    print(f"Schedule:   {args.schedule}  (T={args.timesteps})")
    print(f"Output dir: {output_dir}")
    print(f"Assets dir: {assets_dir}")

    generate_noise_schedule(args, assets_dir, output_dir)
    generate_noising_trajectory(args, assets_dir, output_dir)

    print(f"\nDone. Assets saved to: {assets_dir}")
    print("\nAssets still needed after training:")
    still_needed = [
        "loss_curve.png      → scripts/train.py --assets-dir",
        "samples_final.png   → scripts/train.py --assets-dir",
        "denoising.gif       → scripts/train.py --assets-dir",
        "samples_ddim.png    → scripts/sample.py --ddim --assets-dir",
        "h2d_bandwidth.png         → scripts/benchmark.py --assets-dir",
        "dataloader_comparison.png → scripts/benchmark.py --assets-dir",
        "sampling_comparison.png   → scripts/benchmark.py --assets-dir",
        "training_breakdown.png    → scripts/benchmark.py --assets-dir",
    ]
    for item in still_needed:
        print(f"  {item}")


if __name__ == "__main__":
    main()
